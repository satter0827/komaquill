"""Describe the boundaries used by generation and collection use cases."""

from contextlib import AbstractContextManager
from typing import Any, Protocol
from uuid import UUID

from komaquill.domain.configuration import RuntimeSettings
from komaquill.domain.models import ImageRef, JsonObject, Run, Session
from komaquill.domain.presets import ModelPreset


class GenerationBackend(Protocol):
    """Expose generation operations independently of HTTP or GPU providers."""

    def runtime(self) -> JsonObject: ...
    def queue(self) -> list[list[Any]]: ...
    def history(self) -> JsonObject: ...
    def submit(self, graph: JsonObject, ui: JsonObject, run_id: str) -> str: ...
    def image(self, reference: ImageRef) -> bytes: ...


class RunRepository(Protocol):
    """Keep image checkpoints and request state within one locking boundary."""

    def lock(self) -> AbstractContextManager[Any]: ...
    def load(self, unreadable: list[UUID | str] | None = None) -> list[Run]: ...
    def read(self, run_id: UUID) -> Run: ...
    def save(self, run: Run) -> None: ...
    def conditions(self, run: Run, prompt: list[Any]) -> None: ...
    def prepare(self, run: Run, graph: JsonObject, ui: JsonObject) -> None: ...
    def images(self, backend: GenerationBackend, run: Run, record: JsonObject) -> list[str]: ...


class Workspace(Protocol):
    """Supply a bound configuration and its generation dependencies."""

    @property
    def repository(self) -> RunRepository: ...
    def settings(self) -> RuntimeSettings: ...
    def configured(self, settings: RuntimeSettings | None = None) -> "Workspace": ...
    def identity(self) -> JsonObject: ...
    def prepared_assets(self, session: Session) -> dict[str, ModelPreset]: ...
    def prepare(
        self,
        prompt: str,
        negative: str | None,
        seed: int,
        run_id: str,
        profile_name: str | None = None,
    ) -> tuple[JsonObject, JsonObject]: ...
    def stop_requested(self, session: Session) -> bool | None: ...
